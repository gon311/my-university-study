# 표본 20개에 대해 기준가격 (x), 비교가격 (y)를 입력한 뒤, 
# 비추정량(ratio estimator)의 비 (r=\bar y/\bar x\) 를 구하고 
# 각 관측치의 (y-rx), ((y-rx)^2)를 계산

# 모집단의 크기와 표본 크기 
N = 1000
n = 20

# 데이터 입력
apt <- data.frame(
  id = 1:20, 
  x = c(
    6.7, 8.2, 7.9, 6.4, 8.3,
    7.2, 6.0, 7.4, 8.1, 9.3,
    8.2, 6.8, 7.4, 7.5, 8.3,
    9.1, 8.6, 7.9, 6.3, 8.9
  ),
  y = c(
    7.1, 8.4, 8.2, 6.9, 8.4,
    7.9, 6.5, 7.6, 8.9, 9.9,
    9.1, 7.3, 7.8, 8.3, 8.9,
    9.6, 8.7, 8.8, 7.0, 9.4
  )
)


# 표본평균
x_bar = mean(apt$x) # 7.725
y_bar = mean(apt$y) # 8.235


# 표준편차 
x_sd = sd(apt$x) # 0.947
y_sd = sd(apt$y) # 0.957

# 상관계수 
rho = cor(apt$x, apt$y) # 0.966

# 비추정값 r
ratio = y_bar / x_bar  # 1.066

# r의 분산 추정량 
V_r <- ((N - n) / N) *
  (1 / n) *
  (1 / x_bar^2) *
  (y_sd^2 +
     ratio^2 * x_sd^2 -
     2 * ratio * rho * x_sd * y_sd)
