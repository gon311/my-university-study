# ------------------------------------------------------------
# 1. 단순선형회귀모형의 적합 (Simple Linear Regression)
# 독립변수(x)가 종속변수(y)에 미치는 영향을 선형 방정식으로 모델링합니다.
# ------------------------------------------------------------
x = c(20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40, 42)
y = c(8.4, 9.5, 11.8, 10.4, 13.3, 14.8, 13.2, 14.7, 16.4, 16.5, 18.9, 18.5) 

# lm(): 선형모형(Linear Model) 적합 함수. y를 x로 설명하는 회귀식을 추정합니다.
lm.out = lm(y~x)

# 산점도(Scatter plot)를 그리고, 추정된 회귀직선(abline)을 겹쳐서 시각화합니다.
plot(x, y)
abline(lm.out)

# cor.test(): x와 y 사이의 피어슨 상관계수를 계산하고 유의성을 검정합니다.
cor.test(y, x)
# [출력 결과 해석]
# p-value = 3.211e-07 (0.05보다 매우 작음): 두 변수 간에 유의미한 선형 상관관계가 존재함.
# cor = 0.9663498: x와 y는 매우 강한 양의 상관관계를 가짐.

# summary(): 추정된 회귀계수(절편, 기울기), R-squared(설명력), t-검정 결과 등 회귀분석의 핵심 요약을 제공합니다.
summary(lm.out)
# [출력 결과 해석]
# [1] Residuals (잔차 분포)
# - 실제 관측값과 회귀모형의 예측값 간의 오차.
# - 최소, 1사분위, 중앙, 3사분위, 최댓값을 보여주며, 중앙값(Median)이 0에 가까울수록(-0.3233) 대칭적으로 잘 적합되었음을 의미합니다.

# [2] Coefficients (회귀계수 추정 및 유의성 검정)
# - (Intercept) 절편: -0.28928. x가 0일 때 y의 기댓값. (p-value가 0.817로 0.05보다 커서 통계적으로 유의하지 않음)
# - x (기울기): 0.45664. x가 1단위 증가할 때마다 y가 평균적으로 약 0.457 증가함을 의미.
# - Pr(>|t|) 3.21e-07 *** : 기울기에 대한 p-value. 유의수준 0.05보다 매우 작아, x가 y에 미치는 영향이 통계적으로 매우 유의미합니다.

# [3] 모형의 평가 지표 (적합도)
# - Residual standard error (0.9193): 잔차의 표준오차. 데이터들이 추정된 회귀직선 주변에 평균적으로 약 0.92 정도 퍼져있음을 의미합니다.
# - Multiple R-squared (0.9338): 결정계수(R^2). 독립변수 x가 종속변수 y 변동의 약 93.4%를 설명하고 있습니다 (매우 강한 설명력).
# - F-statistic p-value (3.211e-07): 회귀모형 전체의 통계적 유의성(ANOVA)을 나타냅니다. p<0.05이므로 추정된 선형 모형 자체가 유의미합니다.

# ------------------------------------------------------------
# 2. 회귀의 유의성 검정 (ANOVA for Regression)
# 분산분석(ANOVA) 표를 통해 모형 전체가 통계적으로 유의한지 평가합니다.
# ------------------------------------------------------------
anova(lm.out)
# [출력 결과 해석] 회귀제곱합(SSR)과 오차제곱합(SSE)을 분리하여 F-검정을 수행합니다.

# 총제곱합(SST) 수동 계산 확인 과정
# > 119.275 + 8.451  # 분산분석표의 SSR + SSE = SST
#[1] 127.726

# (length(x)-1)*var(y) # y의 표본분산 식을 이용한 편차제곱합 계산 (SST와 동일)
# [1] 127.7267


# ------------------------------------------------------------
# 3. 신뢰구간과 예측구간 (Confidence and Prediction Intervals)
# 추정된 모형을 바탕으로 모수(회귀계수)나 새로운 값에 대한 구간을 추정합니다.
# ------------------------------------------------------------
# 1) 회귀계수(베타0, 베타1)에 대한 95% 신뢰구간 추출
confint(lm.out, level=0.95)
# 0.370997 ~ 0.5433898

# 예측을 위한 새로운 데이터 포인트 설정
newdata = data.frame(x=30)

# 2) 신뢰구간 (Confidence Interval): x=30일 때, y의 '평균(기댓값)'이 존재할 구간
predict(lm.out, newdata, interval="confidence")
# 12.81254 ~ 14.00751


# 3) 예측구간 (Prediction Interval): x=30일 때, '개별 관측치' y가 존재할 구간
# (평균을 추정하는 것보다 개별 값을 예측하는 것이 오차가 크기 때문에 예측구간이 더 넓습니다)
predict(lm.out, newdata, interval="prediction")
# 11.2763 ~ 15.54375

# ------------------------------------------------------------
# 4. 공분산분석(ANCOVA)을 이용한 처리효과 검정
# 분산분석(기계의 차이)과 회귀분석(원사 두께의 영향)을 결합하여, 
# 연속형 공변량(du)의 영향을 통제한 상태에서 범주형 변수(machine)의 순수 효과를 검정합니다.
# ------------------------------------------------------------
du <- c(20, 25, 24, 25, 32, 22, 28, 22, 30, 28, 21, 23, 26, 21, 15)   # 공변량(연속형)
gang <- c(36, 41, 39, 42, 49, 40, 48, 39, 45, 44, 35, 37, 42, 34, 32) # 종속변수
machine <- c("1", "2", "3")                                           # 처리(범주형)
machine <- rep(machine, c(5, 5, 5))
textile.data <- data.frame(du, gang, machine)

# 기계(범주)별 강도(종속변수)의 차이를 상자그림으로 시각화
boxplot(gang ~ machine)

# 공변량(du)과 종속변수(gang)의 산점도를 기계별로 색상을 다르게 하여 시각화
plot(du, gang, col=machine, pch=19, xlab="원사의 두께(du)", ylab="강도(gnag)",
     main="기계별 원사의 두께와 강도")
legend("topleft", legend = c("기계1", "기계2", "기계3"), col = 1:3, pch = 19)

# [모델 1] 일원배치 분산분석 (One-way ANOVA)
# 원사의 두께(du)가 미치는 영향을 무시하고, 단순히 기계(machine)에 따른 차이만 분석합니다.
oneway.out = aov(gang~machine) 
summary(oneway.out)
# [출력 결과 해석]
# - machine의 Pr(>F) 값이 0.0442로 유의수준 0.05보다 작습니다.
# - 해석: 원사의 두께(du)라는 변수를 아예 무시하고 분석했을 때는 "기계 종류에 따라 원사 강도의 평균 차이가 유의미하다"는 결론이 나옵니다. 
# - Residuals(잔차)의 Sum Sq(오차제곱합)가 206.0으로 상당히 큽니다. 설명되지 않은 변동이 많다는 뜻입니다.

# [모델 2] 공분산분석 (ANCOVA)
# 원사의 두께(du)가 강도에 미치는 영향을 먼저 통제(반영)한 후, 기계(machine) 간의 순수한 차이를 분석합니다.
# 일반적으로 공변량을 추가하면 오차 분산이 줄어들어 처리 효과(기계 차이)를 더 정확하게 검정할 수 있습니다.
anova <- aov(gang ~ du+machine, data=textile.data) 
summary(anova)
# [출력 결과 해석]
# - du (원사 두께, 공변량): Pr(>F) 값이 2.96e-07로 매우 작아, 강도에 미치는 영향력이 통계적으로 매우 큽니다.
# - machine (기계, 처리): Pr(>F) 값이 0.118로 0.05보다 커졌습니다. 통계적으로 유의하지 않게 바뀌었습니다.
# - Residuals(잔차) Sum Sq: 206.0 -> 27.99로 획기적으로 줄어들었습니다. 오차가 크게 줄어 분석의 정밀도가 높아졌습니다.

# lattice 패키지를 이용한 그룹별 회귀 시각화
# 기계(machine) 종류별로 패널을 나누어 du와 gang의 산점도 및 각각의 회귀직선을 그립니다.
# (기계별 기울기가 평행한지, 절편에 차이가 있는지 직관적으로 확인 가능)
library(lattice)
xyplot(gang ~ du | machine, panel = function(x, y, ...) {
  panel.xyplot(x, y, ...) 
  panel.lmline(x, y, ...)
})


