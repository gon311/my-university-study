# 일원배치 분산분석만 봤을 때는 기계마다 성능 차이가 있는 줄 알았지만, 
# 공분산분석을 통해 '원사 두께(du)'라는 외부 요인을 통제(고정)하고 나니, 
# 사실 기계 자체의 성능(강도) 차이는 통계적으로 유의미하지 않았다는 진짜 결론을 얻게 되었습니다.
# 즉, 기계 성능이 달랐던 게 아니라 들어가는 원사의 두께가 달랐기 때문에 강도 차이가 발생했던 것입니다.