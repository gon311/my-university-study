# ============================================================
# 2.1 독립 이표본 t-검정 (Independent Two-Sample t-test)
# 목적: 서로 독립인 두 집단(sample1, sample2)의 평균 차이가 유의미한지 검정
# ============================================================

# 1) 데이터 입력 (각 10개의 표본)
sample1 = c(10.2, 10.5, 10.3, 10.8, 9.8, 10.6, 10.7, 10.2, 10.0, 10.1) # 생산 직후 약효
sample2 = c(9.8, 9.6, 10.1, 10.2, 10.1, 9.7, 9.5, 9.6, 9.8, 9.9)       # 1년 후 약효

# 2) 커널 밀도 추정 그래프(Density Plot)로 분포 시각화 비교
# lty: 선 스타일(1=실선, 2=점선), ylim: y축 범위 지정
plot(density(sample1), lty=1, ylim=c(0, 1.5), main="약효 분포 비교", xlab="약효") # sample1 기준 캔버스 생성 및 실선 출력
lines(density(sample2), lty=2, ylim=c(0, 1.5)) # 기존 그래프에 sample2를 점선으로 겹쳐서 출력

# 3) 박스플롯(Boxplot)으로 상자수염 그림 비교
# ylab: y축 라벨, names: 각 박스 이름, main: 그래프 제목
boxplot(sample1, sample2, ylab="약효", 
        names = c("sample1", "sample2"), main="생산 직후와 1년 후의 약효")

# 4) 등분산성을 가정한 독립 이표본 t-검정 수행
# var.equal = TRUE: 두 집단의 분산이 동일하다고 가정 (Student's t-test)
# 기본 설정: 양측검정(two.sided), 귀무가설(H0): 두 집단의 평균 차이는 0이다.
t.test(sample1, sample2, var.equal = TRUE)

# 5) 양측검정 임계값(Critical Value) 수동 계산
# qt(p, df, lower.tail): 자유도(df)가 18인 t-분포에서 상위 2.5% 위치의 t-값 계산
# df = (10 - 1) + (10 - 1) = 18
# lower.tail = FALSE: 오른쪽 꼬리 확률(0.025)에 해당하는 기각역 기준값 반환
qt(0.025, 18, lower.tail = FALSE) # 결과: 약 2.1009 (검정통계량이 2.1009보다 크면 귀무가설 기각)


# ============================================================
# 2.2 짝지어진 t-검정 (Paired t-test)
# 목적: 동일한 대상의 전/후 비교 등 서로 쌍을 이루는 데이터의 차이(diff) 평균 검정
# ============================================================

# 1) 짝지어진 데이터 입력 및 차이값(diff) 계산
a = c(13.2, 8.2, 10.9, 14.3, 10.7, 6.6, 9.5, 10.8, 8.8, 13.3) # 처리 전 (또는 A 조건)
b = c(14.0, 8.8, 11.2, 14.2, 11.8, 6.4, 9.8, 11.3, 9.3, 13.6) # 처리 후 (또는 B 조건)
diff = b - a # 두 조건 간의 차이 (b가 a보다 더 큰지 확인하기 위함)

# 2) 차이(diff) 데이터의 박스플롯 출력
boxplot(diff, ylab="차이", main="마모도 비교")

# 3) 단측검정(오른쪽) 수행
# mu = 0: 귀무가설(H0): 차이의 평균은 0이다.
# alternative = "greater": 대립가설(H1): 차이의 평균은 0보다 크다 (b > a)
# t.test(a, b, paired = TRUE, alternative = "less") 와 동일한 연산
t.test(diff, mu=0, alternative="greater")

# 4) 단측검정(유의수준 5%) 임계값 수동 계산
# 자유도(df) = 쌍의 개수 - 1 = 10 - 1 = 9
qt(0.05, 9, lower.tail = FALSE) # 결과: 약 1.8331 (검정통계량이 1.8331보다 크면 귀무가설 기각)


# ============================================================
# 2.3 분산비 검정 (F-test for Equal Variances)
# 목적: 두 집단의 분산(변동성)이 서로 같은지(등분산성) 검정
# ============================================================

# 1) 데이터 분포 시각화 (산출된 데이터의 퍼짐 정도 비교)
boxplot(sample1, sample2, ylab="약효", 
        names = c("sample1", "sample2"), main="생산 직후와 1년 후의 약효")

# 2) F-검정 수행 (두 집단의 표본분산의 비율 s1^2 / s2^2 을 측정)
# 귀무가설(H0): 두 집단의 분산은 같다 (Ratio = 1)
var.test(sample1, sample2)

# 3) 양측검정(유의수준 5%) F-분포 임계값 수동 계산
# qf(p, df1, df2, lower.tail): 분자 자유도(9), 분모 자유도(9)인 F-분포의 상위 2.5% 임계값
# df1 = n1 - 1 = 9, df2 = n2 - 1 = 9
qf(0.025, 9, 9, lower.tail = FALSE) # 결과: 약 4.0260 (F 통계량이 4.0260보다 크면 등분산 가정 기각)