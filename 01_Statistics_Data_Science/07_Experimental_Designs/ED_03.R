# ============================================================
# 실험계획과 응용 Chapter 3: 일원배치법 (One-Way ANOVA)
# ============================================================

# ------------------------------------------------------------
# [1단계] 데이터 정의 및 전처리
# ------------------------------------------------------------

# 1. 인자 수준(Factor Level)별 반응치(마모량 등) 벡터 생성
# 각 수준(a1, a2, a3, a4)에서 4회씩 반복 측정(총 N=16)
a1 = c(1.93, 2.38, 2.20, 2.25) # 수준 a1의 데이터 (4개)
a2 = c(2.55, 2.72, 2.75, 2.70) # 수준 a2의 데이터 (4개)
a3 = c(2.40, 2.68, 2.32, 2.28) # 수준 a3의 데이터 (4개)
a4 = c(2.33, 2.38, 2.28, 2.25) # 수준 a4의 데이터 (4개)

# 2. 모든 반응치 데이터를 하나의 단일 벡터로 통합 (총 16개 데이터)
wear = c(a1, a2, a3, a4)

# 3. 요인 수준 이름 라벨링 준비
group = c("a1", "a2", "a3", "a4")

# 4. 각 수준별 라벨을 데이터 개수에 맞춰 반복 생성
# rep(x, times): x의 각 요소를 times에 지정된 횟수만큼 반복
# c(4, 4, 4, 4) -> "a1" 4번, "a2" 4번, "a3" 4번, "a4" 4번 반복
group <- rep(group, c(4, 4, 4, 4))

# 5. 분석용 데이터 프레임(Data Frame) 생성
wear.dat <- data.frame(group, wear)

# 6. 메모리 로드 (data.frame 변수를 직접 참조 가능하게 지정)
# 주의: 작업 완료 후에는 detach(wear.dat) 실행을 권장합니다.
attach(wear.dat)


# ------------------------------------------------------------
# [2단계] 기술통계량 확인 및 데이터 시각화
# ------------------------------------------------------------

# 7. 그룹별 합계 및 평균 계산
# tapply(반응변수, 그룹변수, 적용함수)
tapply(wear, group, sum)  # 각 수준(a1~a4)별 마모량 합계 (Ti.)
tapply(wear, group, mean) # 각 수준(a1~a4)별 마모량 평균 (y_bar i.)

# 8. 전체 데이터의 총합(T..) 및 총평균(y_bar ..) 산출
sum(wear)
mean(wear)

# 9. 그룹별 분포 시각화 (상자수염그림, Boxplot)
# 요인(group) 수준에 따른 마모량(wear)의 중앙값, 흩어짐 정도, 이상치 확인
boxplot(wear ~ group)


# ------------------------------------------------------------
# [3단계] 분산분석(ANOVA) 수행 및 해석
# ------------------------------------------------------------

# 10. 일원배치 분산분석(ANOVA) 모델 적합
# 귀무가설(H0): 모든 수준의 평균은 같다. (μ1 = μ2 = μ3 = μ4)
# 대립가설(H1): 적어도 하나의 수준의 평균은 다르다.
aov.out = aov(wear ~ group, data=wear.dat)

# 11. 분산분석표(ANOVA Table) 출력
# 자유도(Df), 제곱합(Sum Sq), 평균제곱(Mean Sq), F-값, p-value 확인
summary(aov.out)

# 12. F-분포의 이론적 기각역(Critical Value) 산출
# qf(p, df1, df2): 유의수준 α = 0.01 (1 - 0.99) 기준 임계값 계산
# df1 = 처리 자유도(k-1 = 3), df2 = 오차 자유도(N-k = 12)
qf(0.99, df1=3, df2=12)

# 13. F 통계량에 따른 p-value(유의확률) 직접 계산 연습
# pf(q, df1, df2, lower.tail=FALSE): P(X > q) 영역의 넓이를 산출
pf(5.95, df1=3, df2=12, lower.tail=F)   # 임계치(5.95) 근처에서의 p-value
pf(8.785, df1=3, df2=12, lower.tail=F)  # 실제 ANOVA에서 얻은 F값(8.785)의 p-value
# -> p-value(약 0.0024) < α(0.01) 이므로, 유의수준 1%에서 귀무가설을 기각함


# ------------------------------------------------------------
# [4단계] 가정 검정 및 추가 일원배치 검정
# ------------------------------------------------------------

# 14. 일원배치 평균 비교 검정 (oneway.test)
# var.equal = TRUE: 각 그룹의 분산이 서로 같다는 '등분산성 가정'하에 검정 수행
# (aov() 함수 결과 및 F-검정 수치와 동일한 p-value 결과 제공)
oneway.test(wear ~ group, var.equal = TRUE)

# 15. 바틀렛 등분산 검정 (Bartlett's Test for Homogeneity of Variances)
# 분산분석(ANOVA)의 기본 전제 조건인 '각 그룹의 분산이 동일한가'를 검정
# 귀무가설(H0): 모든 집단의 분산이 같다. (σ1² = σ2² = σ3² = σ4²)
# 대립가설(H1): 적어도 한 집단의 분산은 다르다.
# -> p-value가 0.05보다 크면 등분산 가정을 만족하여 ANOVA 결과를 신뢰할 수 있음
bartlett.test(wear ~ group, data=wear.dat)