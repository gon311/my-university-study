# 작업 디렉토리 설정 (데이터 파일 위치 경로)
setwd("~/KNOU_stat/R_codes")

# 데이터 로드
dat0 <- read.csv("biostat_ex_data.csv")

# 데이터 가공을 위한 dplyr 패키지 로드
library(dplyr)

# 범주형 변수 일괄 factor 변환
dat1 <- dat0 %>% mutate_at(vars(sex, Recur, stage, smoking,
                                obesity, Recur_1y,
                                post.CA19.9.binary,
                                post.CA19.9.3grp),
                           as.factor)


# ------------------------------------------------------------
# [1. 데이터의 시각화 및 정규성 확인]
# ------------------------------------------------------------

library(ggplot2)

# 히스토그램 생성: 몸무게(weight)의 분포 형태 확인
# breaks=seq(40, 100, 10): 40부터 100까지 10 간격으로 구간 설정
ggplot(dat1) + 
  geom_histogram(aes(x = weight), color = "black", fill = "skyblue", breaks = seq(40, 100, 10))

# [복습 포인트]
# - 히스토그램 시각화 결과: 분포가 좌우 대칭에 가깝고 꼬리가 두껍지 않아 정규성을 만족한다고 볼 수 있음.
# - 연속형 데이터를 비교할 때는 정규성 여부에 따라 모수적 방법(t-test)과 비모수적 방법(Wilcoxon test)을 선택함.


# ------------------------------------------------------------
# [2. 독립표본 t-검정 (Two-sample t-test)]
# 질문: 남성과 여성 췌장암 환자 간 몸무게 평균의 차이가 있는가?
# - 귀무가설 (H0): \mu_male = \mu_female (두 집단의 모평균은 같다)
# - 대립가설 (H1): \mu_male ≠ \mu_female (두 집단의 모평균은 다르다)
# ------------------------------------------------------------

# (1) Welch's t-test (이분산 가정 - R의 t.test 기본값)
# 두 집단의 분산이 다르다고 가정하고 검정 (가장 안정적이고 범용적인 방법)
t.test(weight ~ sex, data = dat1)

# [결과 해석 및 복습 포인트]
# 1. t = -12.734, 자유도(df) = 126.51
# 2. p-value < 2.2e-16 (유의수준 0.05보다 훨씬 작음) -> 귀무가설(H0) 기각.
# 3. 95% 신뢰구간: [-24.38, -17.82] (0을 포함하지 않음)
# 4. 표본 평균: 여성(sex=0) = 54.33kg, 남성(sex=1) = 75.43kg
# -> 결론: 남성과 여성 췌장암 환자의 몸무게 모평균은 통계적으로 유의미하게 다르다.


# (2) Student's t-test (등분산 가정 - var.equal = TRUE)
# 두 집단의 분산이 같다는 전제하에 수행하는 검정
t.test(weight ~ sex, data = dat1, var.equal = TRUE)

# [결과 해석 및 복습 포인트]
# 1. t = -12.028, 자유도(df) = 154
# 2. p-value < 2.2e-16 -> 귀무가설 기각 (결론은 Welch's t-test와 동일)


# [★ 통계학적 유의점]
# 검정 대상은 '현재 수집된 표본데이터 속 남녀 156명의 평균 차이'가 아니라,
# 이 표본이 추출된 '전체 췌장암 환자 모집단에서의 남녀 몸무게 모평균 차이'에 대한 추론임.


# ------------------------------------------------------------
# [3. 윌콕슨 순위합 검정 (Wilcoxon rank-sum test / Mann-Whitney U test)]
# - 정규성 가정을 만족하지 못하거나 서열척도 데이터일 때 사용하는 비모수적 방법
# - 실제 데이터값 대신 '순위(Rank)'를 기반으로 두 집단의 위치(Location) 차이를 검정
# ------------------------------------------------------------

wilcox.test(weight ~ sex, data = dat1)

# [결과 해석 및 복습 포인트]
# 1. W = 424, p-value < 2.2e-16
# 2. p-value < 0.05 이므로 비모수 검정에서도 두 집단의 분포/위치가 유의미하게 다르다는 결론을 얻음.


# ============================================================
# EXTRA PRACTICE: 비모수 검정(Wilcoxon test)의 주의점 복습
# ============================================================

# [개념 심화]
# 윌콕슨 순위합 검정은 '단순히 중앙값(Median)만의 비교'가 아니라 
# '전체적인 분포 형태와 순위합'을 비교하는 검정임.
# 따라서 두 집단의 중앙값이 완전히 같아도 분포의 형태(치우침 등)가 다르면 유의미한 차이가 나올 수 있음.


# ------------------------------------------------------------
# 예시 1) 중앙값은 0으로 동일하지만 분포 형태가 극단적으로 다른 경우
# ------------------------------------------------------------

x1 <- c(rep(-1, 10), 0, rep(10, 10))   # -1이 10개, 0이 1개, 10이 10개
x2 <- c(rep(-10, 10), 0, rep(1, 10))   # -10이 10개, 0이 1개, 1이 1개

median(x1)  # 결과: 0
median(x2)  # 결과: 0

# 두 집단의 중앙값은 0으로 완전히 동일함
wilcox.test(x1, x2)  

# [결과 해석]
# p-value = 0.01009 (< 0.05)
# -> 중앙값이 같음에도 불구하고 전체적인 값들의 순위 분포가 달라서 귀무가설이 기각됨.


# ------------------------------------------------------------
# 예시 2) 모집단의 중앙값을 0으로 맞춘 후 시뮬레이션 추출
# ------------------------------------------------------------

set.seed(2026)  # 난수 생성 고정 (재현성 확보)

# 0부터 1 사이의 연속균등분포(Uniform distribution)에서 10,000개 추출
xx <- runif(10000, 0, 1)  

# 모집단 1과 모집단 2 생성 (둘 다 0을 기준으로 대칭 또는 대칭 변형 구조)
pop1 <- c(xx, 0, -xx)       # -1 ~ 1 범위의 대칭 분포
pop2 <- c(xx, 0, -100 * xx) # -100 ~ 1 범위로 스케일이 크게 치우친 비대칭 분포

median(pop1)  # 결과: 0
median(pop2)  # 결과: 0

# 분포 확인
hist(pop1)
hist(pop2)

# 각 모집단에서 100개씩 표본 무작위 추출
x11 <- sample(pop1, 100)
x22 <- sample(pop2, 100)

wilcox.test(x11, x22)  

# [결과 해석]
# p-value = 0.06331 (> 0.05)
# -> 난수 및 표본 추출 상태에 따라 p-value가 달라지며, 
#    분포 형태 차이에 의해 중앙값이 같더라도 비모수 검정 해석 시 주의가 필요함을 시사함.